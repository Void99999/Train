/**
 * Builds a single self-contained HTML file that runs by double-clicking it.
 *
 *     node tools/build-standalone.js
 *     -> last-train-standalone.html
 *
 * The problem it solves: LAST TRAIN is delivered as native ES modules, and a
 * browser refuses to load those over `file://`. Normally that means a local
 * server. For someone who just wants to play, that is one obstacle too many.
 *
 * How it works: every module's source is embedded as a string. At load time a
 * small resolver walks the import graph depth-first, turns each module into a
 * Blob URL, and rewrites the relative specifiers in its dependents to point at
 * those URLs. Blob URLs are same-origin regardless of where the page came
 * from, so the module graph loads from a file on disk.
 *
 * Nothing about the module code is rewritten except the specifier strings, so
 * the standalone build runs exactly the same code as the served build. There
 * is no bundler, no transpiler and no second copy of the game to keep in sync.
 */

import { readFile, writeFile, readdir } from "node:fs/promises";
import { join, dirname, relative, posix } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = fileURLToPath(new URL("..", import.meta.url));
const ENTRY = "src/main.js";
const OUTPUT = "last-train-standalone.html";

/**
 * Matches a relative module specifier in an import or export statement.
 * Restricted to specifiers beginning with "./" or "../" so it cannot match a
 * stray `from "x"` inside an unrelated string literal.
 */
const SPECIFIER = /(\bfrom\s*|\bimport\s*\(?\s*)(["'])(\.\.?\/[^"']*)\2/g;

/** Every .js file under these directories is embedded. */
const SOURCE_DIRECTORIES = ["src", "vendor"];

async function collectFiles(directory) {
  const entries = await readdir(join(ROOT, directory), { withFileTypes: true });
  const files = [];
  for (const entry of entries) {
    const path = posix.join(directory, entry.name);
    if (entry.isDirectory()) files.push(...(await collectFiles(path)));
    else if (entry.name.endsWith(".js")) files.push(path);
  }
  return files;
}

/** Resolves a relative specifier against the importing module's path. */
function resolveSpecifier(fromPath, specifier) {
  return posix.normalize(posix.join(posix.dirname(fromPath), specifier));
}

/**
 * Depth-first walk of the import graph, purely to verify at build time that
 * the graph is acyclic. The runtime resolver is recursive and a cycle would
 * hang it, so it is worth failing loudly here instead.
 */
function assertNoCycles(sources) {
  const visiting = new Set();
  const done = new Set();

  const visit = (path, trail) => {
    if (done.has(path)) return;
    if (visiting.has(path)) {
      throw new Error(`Circular import: ${[...trail, path].join(" -> ")}`);
    }
    visiting.add(path);

    const source = sources.get(path);
    if (source === undefined) throw new Error(`Missing module: ${path}`);

    for (const match of source.matchAll(SPECIFIER)) {
      visit(resolveSpecifier(path, match[3]), [...trail, path]);
    }

    visiting.delete(path);
    done.add(path);
  };

  visit(ENTRY, []);
}

/**
 * Escapes a source file for embedding inside a <script> block.
 * JSON.stringify handles quotes and newlines; the closing-tag guard stops an
 * embedded "</script" from ending the block early and truncating the file.
 */
function embed(source) {
  return JSON.stringify(source).replaceAll("</script", "<\\/script");
}

async function main() {
  const paths = (await Promise.all(SOURCE_DIRECTORIES.map(collectFiles))).flat();
  const sources = new Map();
  for (const path of paths) {
    sources.set(path, await readFile(join(ROOT, path), "utf8"));
  }

  assertNoCycles(sources);

  const html = await readFile(join(ROOT, "index.html"), "utf8");
  const css = await readFile(join(ROOT, "src/ui/styles.css"), "utf8");

  if (css.toLowerCase().includes("</style")) {
    throw new Error("styles.css contains '</style' and cannot be embedded");
  }

  const registry = [...sources.entries()]
    .map(([path, source]) => `  ${JSON.stringify(path)}: ${embed(source)}`)
    .join(",\n");

  const loader = `
<script>
/*
  Standalone loader. Generated by tools/build-standalone.js - do not edit this
  file directly; change the sources and rebuild.
*/
(function () {
  "use strict";

  var SOURCES = {
${registry}
  };

  var ENTRY = ${JSON.stringify(ENTRY)};
  var SPECIFIER = ${SPECIFIER.toString()};
  var urls = Object.create(null);

  function dirname(path) {
    var index = path.lastIndexOf("/");
    return index === -1 ? "" : path.slice(0, index);
  }

  /* Minimal POSIX path normalisation: enough for "./" and "../" specifiers. */
  function normalise(path) {
    var parts = path.split("/");
    var stack = [];
    for (var i = 0; i < parts.length; i += 1) {
      var part = parts[i];
      if (part === "" || part === ".") continue;
      if (part === "..") stack.pop();
      else stack.push(part);
    }
    return stack.join("/");
  }

  function resolve(path) {
    if (urls[path]) return urls[path];

    var source = SOURCES[path];
    if (source === undefined) throw new Error("Missing embedded module: " + path);

    var base = dirname(path);
    var rewritten = source.replace(SPECIFIER, function (match, prefix, quote, specifier) {
      return prefix + quote + resolve(normalise(base + "/" + specifier)) + quote;
    });

    var url = URL.createObjectURL(new Blob([rewritten], { type: "text/javascript" }));
    urls[path] = url;
    return url;
  }

  function fail(error) {
    console.error(error);
    var box = document.getElementById("boot-error");
    box.hidden = false;
    box.textContent = "LAST TRAIN konnte nicht starten / could not start:\\n\\n" + error.message;
  }

  try {
    import(resolve(ENTRY))
      .then(function (module) { return module.boot(); })
      .catch(fail);
  } catch (error) {
    fail(error);
  }
})();
</script>`;

  const note =
    "<!-- Generated by tools/build-standalone.js. Everything the game needs is\n" +
    "     inside this file: no server, no installation, no internet.\n" +
    "     Do not edit directly - change the sources and rebuild. -->";

  // Both replacements use a function rather than a replacement string. The
  // embedded sources contain "$" sequences, and in a replacement string "$&",
  // "$'" and "$`" splice in parts of the surrounding text - which silently
  // corrupts megabytes of JavaScript into something that will not parse.
  const styleBlock = note + "\n    <style>\n" + css + "\n    </style>";
  let output = html.replace(
    '<link rel="stylesheet" href="src/ui/styles.css" />',
    () => styleBlock,
  );

  // Replace the module bootstrap with the standalone loader.
  const loaderBlock = loader.trim();
  output = output.replace(/<script type="module">[\s\S]*?<\/script>/, () => loaderBlock);

  if (output.includes('src="src/main.js"') || output.includes("type=\"module\"")) {
    throw new Error("index.html bootstrap was not replaced - check the markers");
  }

  await writeFile(join(ROOT, OUTPUT), output, "utf8");
  console.log(
    `${OUTPUT} written: ${sources.size} modules, ${(output.length / 1024 / 1024).toFixed(2)} MB`,
  );
}

await main();
